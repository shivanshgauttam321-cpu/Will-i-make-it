"""
Energy Model for EV Route Planning
====================================
Physics-based segment-level energy prediction with uncertainty quantification.

UNITS & CONVENTIONS
-------------------
- Distance: km (converted to m internally)
- Speed: km/h (converted to m/s)
- Mass: kg
- Energy: kJ internally, converted to kWh for output (1 kWh = 3600 kJ)
- Gradient: % (rise/run × 100); positive = uphill
- Power: kW

ASSUMPTIONS
-----------
1. Rolling resistance: F_roll = Crr × m × g  (constant, independent of speed)
2. Aerodynamic drag: F_aero = 0.5 × ρ_air × Cd × A × v²  (ρ=1.20 kg/m³ at 25°C)
3. Gradient force: F_grad = m × g × sin(θ) ≈ m × g × gradient/100 for small angles
4. Drivetrain efficiency applied to total traction demand (excluding regen path)
5. Regen: only on downhill segments where gradient < -0.5%, capped at regen_efficiency
6. Auxiliary load (AC + 12V electronics) applied continuously for segment duration
7. Temperature effect on battery: +5% energy draw per 10°C below 25°C (cold); negligible above 25°C
8. No acceleration modeling (steady-state approximation); urban segments get +15% urban factor
9. P90 uncertainty: multiplicative factor applied to traction energy only (not regen/aux)
   - Derives from a ±σ of 12% relative on traction energy for highway, 18% urban, 20% rural
   - P90 ≈ P50 × exp(σ) where σ is the log-normal shape parameter
   - This is a SYNTHETIC estimate; no validation against independent Indian EV drive-cycle data

KNOWN LIMITATIONS
-----------------
- No road-surface-quality data (potholes add ~3-8% extra rolling loss on typical Indian roads)
- No traffic congestion model beyond road-type factor
- Gradient data is flat-zero for demo unless provided
- Regen model is simplified (no brake blending model)
"""

from __future__ import annotations
import math
from typing import List, Tuple
import numpy as np

from app.models.schemas import (
    VehicleProfile, RouteSegment, EnergyPredictRequest,
    EnergyPredictResponse, SegmentEnergyResult
)

# Physical constants
G = 9.81          # m/s²
RHO_AIR = 1.20    # kg/m³ at ~25°C sea level
KJ_PER_KWH = 3600.0

# Road-type uncertainty σ (log-normal, on traction energy)
ROAD_SIGMA = {
    "highway": 0.12,
    "rural": 0.20,
    "urban": 0.18,
}

# Urban stop-start correction factor (extra energy for acceleration/deceleration)
URBAN_FACTOR = 1.15

DISCLAIMER = (
    "⚠️ SYNTHETIC DATA: All energy estimates are generated by a physics model "
    "with assumed parameters. Uncertainty bands (P90) are derived analytically "
    "from assumed log-normal variance—NOT validated against independent Indian EV "
    "drive-cycle measurements. Do not use for safety-critical decisions."
)

ASSUMPTIONS = [
    "Rolling resistance Crr is constant (independent of speed and temperature)",
    "Air density = 1.20 kg/m³ (standard atmosphere, 25 °C, sea level)",
    "Gradient force uses small-angle approximation (valid up to ±15%)",
    "Drivetrain efficiency is constant (not modeled as a function of torque/speed)",
    "Regen applied only when gradient < -0.5% and vehicle is not urban-crawling",
    "Auxiliary load (AC + 12V) = constant kW for full segment duration",
    "Urban segments carry +15% energy correction for stop-start losses",
    "Temperature correction: +5% traction energy per 10°C below 25°C; 0 above",
    "P90 uncertainty uses log-normal model with σ = 0.12 (highway) / 0.18 (urban) / 0.20 (rural)",
    "P90 coverage is ANALYTICAL — not validated against real Indian EV telemetry",
]


def _speed_ms(kmh: float) -> float:
    return kmh / 3.6


def _temp_correction(ambient_c: float) -> float:
    """Return multiplicative factor for traction energy due to temperature."""
    delta = 25.0 - ambient_c
    if delta <= 0:
        return 1.0
    return 1.0 + 0.005 * delta  # +0.5% per °C below 25


def _p90_factor(sigma: float, confidence: float = 0.90) -> float:
    """
    Log-normal P-factor: P_q = exp(z_q * sigma) where z_q is the standard normal quantile.
    For P90, z=1.282; P95, z=1.645; P99, z=2.326.
    """
    try:
        from scipy.special import ndtri  # type: ignore
        z = float(ndtri(confidence))
    except (ImportError, Exception):
        # Fallback: standard normal quantile approximation
        quantile_map = {0.90: 1.2816, 0.95: 1.6449, 0.99: 2.3263, 0.50: 0.0}
        z = quantile_map.get(round(confidence, 2), 1.2816)
    return math.exp(z * sigma)


def predict_segment(
    seg: RouteSegment,
    vehicle: VehicleProfile,
    ambient_c: float = 25.0,
    confidence: float = 0.90,
    soc_before_pct: float = 100.0,
) -> Tuple[SegmentEnergyResult, float]:
    """
    Predict energy for a single road segment.

    Returns (SegmentEnergyResult, soc_after_pct).
    All intermediate energies are in kJ; output in kWh.
    """
    d_m = seg.distance_km * 1000.0      # distance in metres
    v = _speed_ms(seg.avg_speed_kmh)    # speed in m/s
    m = vehicle.vehicle_mass_kg + vehicle.payload_kg
    grad = seg.gradient_pct / 100.0     # dimensionless rise/run

    # -- Rolling resistance (kJ) --
    f_roll = vehicle.rolling_resistance * m * G
    e_roll_kj = f_roll * d_m / 1000.0  # N·m → kJ

    # -- Aerodynamic drag (kJ) --
    f_aero = 0.5 * RHO_AIR * vehicle.drag_coefficient * vehicle.frontal_area_m2 * v**2
    e_aero_kj = f_aero * d_m / 1000.0

    # -- Gradient (kJ) -- positive = energy cost uphill, negative = energy recovered downhill
    sin_theta = grad / math.sqrt(1 + grad**2)  # exact sine from gradient
    f_grad = m * G * sin_theta
    e_grad_kj = f_grad * d_m / 1000.0

    # -- Urban stop-start correction (applied to traction, not gradient) --
    urban_mult = URBAN_FACTOR if seg.road_type == "urban" else 1.0

    # -- Temperature correction --
    temp_mult = _temp_correction(ambient_c)

    # -- Traction energy (positive = energy needed from drivetrain) --
    traction_kj = (e_roll_kj + e_aero_kj) * urban_mult * temp_mult

    # -- Regen: only if downhill enough and regen_efficiency > 0 --
    regen_kj = 0.0
    if e_grad_kj < 0 and seg.gradient_pct < -0.5:
        # Recover a fraction of gravitational PE on downhill
        regen_kj = e_grad_kj * vehicle.regen_efficiency  # negative value * efficiency → still negative

    # -- Auxiliary load (kJ) = power (kW) × time (h) × 3600 kJ/kWh --
    t_seg_h = seg.distance_km / seg.avg_speed_kmh  # hours
    e_aux_kj = vehicle.ac_load_kw * t_seg_h * KJ_PER_KWH  # kW * h * 3600 = kJ

    # -- Net energy from battery (before drivetrain efficiency) --
    # Uphill: we pay gradient/drivetrain_efficiency; Downhill: we get regen_kj back
    if e_grad_kj >= 0:
        # Uphill or flat: all energy paid at drivetrain efficiency
        gross_kj = (traction_kj + e_grad_kj) / vehicle.drivetrain_efficiency
    else:
        # Downhill: traction paid, regen returned
        gross_kj = traction_kj / vehicle.drivetrain_efficiency + regen_kj

    net_kj = gross_kj + e_aux_kj
    net_kwh = net_kj / KJ_PER_KWH

    # -- P90 (conservative) estimate --
    sigma = ROAD_SIGMA.get(seg.road_type, 0.18)
    p90_factor = _p90_factor(sigma, confidence)
    # Apply uncertainty only to traction + gradient portion (not aux which is deterministic)
    traction_net_kwh = (gross_kj - regen_kj / vehicle.regen_efficiency if vehicle.regen_efficiency > 0 else gross_kj) / KJ_PER_KWH
    aux_kwh = e_aux_kj / KJ_PER_KWH
    net_kwh_p90 = traction_net_kwh * p90_factor + aux_kwh

    # -- SoC update --
    battery_kwh = vehicle.battery_capacity_kwh
    soc_delta = (net_kwh / battery_kwh) * 100.0
    soc_after = max(0.0, min(100.0, soc_before_pct - soc_delta))

    result = SegmentEnergyResult(
        segment_id=seg.segment_id,
        name=seg.name,
        distance_km=seg.distance_km,
        rolling_kj=round(e_roll_kj, 2),
        aero_kj=round(e_aero_kj, 2),
        gradient_kj=round(e_grad_kj, 2),
        aux_kj=round(e_aux_kj, 2),
        regen_kj=round(regen_kj, 2),
        net_kwh=round(net_kwh, 4),
        net_kwh_p90=round(net_kwh_p90, 4),
        soc_after_pct=round(soc_after, 2),
    )
    return result, soc_after


def predict_energy(request: EnergyPredictRequest) -> EnergyPredictResponse:
    """
    Predict total trip energy from a list of segments.
    Returns P50 (expected) and P90 (conservative) totals.
    """
    vehicle = request.vehicle
    ambient_c = request.ambient_temp_c
    confidence = request.confidence_target

    soc = vehicle.soc_start_pct
    segment_results = []
    total_p50 = 0.0
    total_p90 = 0.0

    for seg in request.segments:
        res, soc = predict_segment(seg, vehicle, ambient_c, confidence, soc)
        segment_results.append(res)
        total_p50 += res.net_kwh
        total_p90 += res.net_kwh_p90

    soc_final_p50 = vehicle.soc_start_pct - (total_p50 / vehicle.battery_capacity_kwh) * 100.0
    soc_final_p50 = max(0.0, min(100.0, soc_final_p50))

    soc_final_p90 = vehicle.soc_start_pct - (total_p90 / vehicle.battery_capacity_kwh) * 100.0
    soc_final_p90 = max(0.0, min(100.0, soc_final_p90))

    feasible = soc_final_p90 >= vehicle.soc_reserve_pct

    # Update soc_after_pct per segment for P50 path (already done in loop above)
    return EnergyPredictResponse(
        total_kwh_p50=round(total_p50, 3),
        total_kwh_p90=round(total_p90, 3),
        soc_final_p50_pct=round(soc_final_p50, 2),
        soc_final_p90_pct=round(soc_final_p90, 2),
        feasible=feasible,
        segments=segment_results,
        assumptions=ASSUMPTIONS,
        uncertainty_method=(
            f"Log-normal multiplicative uncertainty on traction energy. "
            f"σ per road type: highway={ROAD_SIGMA['highway']}, "
            f"urban={ROAD_SIGMA['urban']}, rural={ROAD_SIGMA['rural']}. "
            f"P{int(confidence*100)} factor = exp(z × σ). "
            f"SYNTHETIC — not validated against real Indian EV data."
        ),
        data_disclaimer=DISCLAIMER,
    )
